def objects_answer(rows,observed,hosts=(),max_objects=24,path='objects',host_scope='THIS GROUP/ALTERNATIVE'):
    if not isinstance(rows,list) or len(rows)>max_objects:raise ValueError('Invalid object array/capacity')
    keys=[r.get('key') if isinstance(r,dict) else None for r in rows]
    if any(not isinstance(k,str) or not re.fullmatch(r'[A-Za-z][A-Za-z0-9_]{0,63}',k) for k in keys) or len(set(keys))!=len(keys):
        raise ValueError('Use unique short identifier keys for every object')
    collisions=set(keys)&(set(observed)|set(hosts))
    if collisions:raise ValueError(path+': objects contains existing IDs '+str(sorted(collisions))+
        '. Return NEW content definitions only; do not copy furniture/observed records into objects. '
        'Existing hosts are already present and are referenced using attachment.host or relation endpoints.')
    available=set(keys)|set(hosts)|set(observed);out=[]
    for i,r in enumerate(rows):
        at=f'{path}[{i}]({r["key"]})'
        obj={k:text(r.get(k),k) for k in ('key','name','category','variant','distinct_instance_reason','placement_hint')}
        a=r.get('attachment')
        if not isinstance(a,dict) or not isinstance(a.get('kind'),str) or a['kind'] not in ATTACHMENTS:
            raise ValueError(at+'.attachment.kind must be one of '+str(sorted(ATTACHMENTS)))
        kind=a['kind'];host=a.get('host')
        if kind in ('top','seat','shelf','hang'):
            if not isinstance(host,str) or host not in available or host==obj['key']:
                raise ValueError(at+'.attachment.host='+repr(host)+' needs an exact distinct host ID IN '+host_scope+' '
                    'or an observed ID. Allowed IDs: '+str(sorted(available-{obj['key']}))+
                    '. A host outside this declared scope is not available; do not invent or silently change the host.')
        elif host is not None:raise ValueError(at+': '+kind+' requires host=null; being near a wall is not wall mounting')
        aff=r.get('affordances',[])
        # Exact spelling alias seen in both real Qwen replies on 2026-10-24.
        # Keep the raw request/reply intact; annotate the normalized record.
        # This does not infer a host, create an affordance, or repair geometry.
        normalizations=[]
        if isinstance(aff,list):
            normalizations=[dict(field='affordances',original='hang',canonical='hanging',
                reason='exact_hanging_affordance_spelling_alias') for v in aff if v=='hang']
            aff=['hanging' if v=='hang' else v for v in aff]
        if not isinstance(aff,list) or any(not isinstance(v,str) or v not in AFFORDANCES for v in aff):raise ValueError(at+'.affordances must be a subset of '+str(sorted(AFFORDANCES)))
        if normalizations:obj['interface_normalizations']=normalizations
        obj.update(attachment=dict(kind=kind,host=host),affordances=list(dict.fromkeys(aff)));out.append(obj)
    order_objects(out,set(hosts)|set(observed))
    return out


def order_objects(objects,external=()):
    remaining={o['key']:o for o in objects};done=set(external);order=[]
    while remaining:
        ready=[k for k,o in remaining.items() if o['attachment']['host'] is None or o['attachment']['host'] in done]
        if not ready:raise ValueError('Attachment cycle or unknown host: '+str(list(remaining)))
        for k in ready:order.append(remaining.pop(k));done.add(k)
    return order


def relations_answer(rows,available,objects=(),path='relations'):
    """Bind only declared adjacency aliases or an already encoded attachment.

    Redundant support assertions do not become centre-height constraints. The
    installation equation remains in attachment; the binding is saved on the
    containing alternative. Unknown identities are never guessed or dropped.
    """
    if not isinstance(rows,list):raise ValueError('relations must be an array')
    out=[];seen=set();bindings=[];bykey={o['key']:o for o in objects}
    for i,r in enumerate(rows):
        at=f'{path}[{i}]'
        if not isinstance(r,dict):raise ValueError(at+' must be an object')
        a,b,k=r.get('source'),r.get('target'),r.get('kind')
        if not isinstance(a,str) or not isinstance(b,str) or a not in available or b not in available or a==b:
            raise ValueError(at+': invalid endpoints '+json.dumps(dict(source=a,target=b),ensure_ascii=False)+
                '; use two DISTINCT exact IDs from '+str(sorted(available)))
        reason=text(r.get('reason'),at+'.reason')
        canonical=RELATION_ALIASES.get(k,k) if isinstance(k,str) else None
        if canonical in ('on','on_top_of','supported_by'):
            attachment=bykey.get(a,{}).get('attachment',{})
            # Untyped "on" can mean attached (e.g. a cover on a lamp), not
            # necessarily resting on its top. The typed attachment is the ONE
            # installation source. Never turn a redundant "on" into "top".
            allowed={'top'} if canonical=='on_top_of' else {'top','seat','shelf','hang'}
            if attachment.get('host')==b and attachment.get('kind') in allowed:
                bindings.append(dict(path=at,source=a,target=b,original_kind=k,
                    action='redundant_support_assertion_bound_to_existing_attachment',attachment=deepcopy(attachment),reason=reason,
                    physical_installation_verified=False))
                continue
            raise ValueError(at+': '+str(k)+' must agree with the source object attachment.kind/host; '
                'support is not a centre-height relation. Actual attachment: '+str(attachment)+'. '+RELATION_CONTRACT)
        if canonical not in RELATIONS:
            raise ValueError(at+': unsupported kind '+repr(k)+'. '+RELATION_CONTRACT)
        if canonical!=k:bindings.append(dict(path=at,source=a,target=b,original_kind=k,canonical_kind=canonical,
            action='non_directional_adjacency_alias',reason=reason))
        k=canonical
        if (a,b,k) in seen:raise ValueError(at+': duplicate relation '+str((a,b,k)))
        seen.add((a,b,k));out.append(dict(source=a,target=b,kind=k,reason=text(r.get('reason'),'relation.reason')))
    return out,bindings


def furniture_answer(value,case,hypothesis):
    alternatives=value.get('alternatives');observed={o['id'] for o in case['context']};out=[]
    if not isinstance(alternatives,list) or not 1<=len(alternatives)<=2:raise ValueError('alternatives needs 1..2 complete arrangements')
    for ai,alt in enumerate(alternatives):
        if not isinstance(alt,dict) or not isinstance(alt.get('groups'),list) or len(alt['groups'])>4:raise ValueError('Need groups array, maximum 4')
        groups=[];all_keys=set()
        for i,g in enumerate(alt['groups']):
            if not isinstance(g,dict):raise ValueError('group must be an object')
            group=dict(key=f'g{i}',function=text(g.get('function'),'group.function'),reason=text(g.get('reason'),'group.reason'))
            group['objects']=objects_answer(g.get('objects'),observed,path=f'alternatives[{ai}].groups[{i}].objects')
            if not group['objects']:raise ValueError('Omit an empty assembly; an empty overall arrangement uses groups=[]')
            keys={o['key'] for o in group['objects']}
            if all_keys&keys:raise ValueError('Furniture keys must be unique across groups')
            all_keys|=keys;groups.append(group)
        if len(all_keys)>12:raise ValueError('Furniture capacity 12 exceeded; do not silently truncate')
        relations,bindings=relations_answer(alt.get('relations',[]),all_keys|observed,
            [o for g in groups for o in g['objects']],path=f'alternatives[{ai}].relations')
        out.append(dict(description=text(alt.get('description'),'alternative.description'),hypothesis=deepcopy(hypothesis),groups=groups,
            relations=relations,relation_bindings=bindings))
    return out


