def hypotheses_answer(value):
    rows=value.get('hypotheses')
    if not isinstance(rows,list) or not 1<=len(rows)<=2:raise ValueError('hypotheses needs 1..2 records')
    result=[]
    for i,r in enumerate(rows):
        if not isinstance(r,dict):raise ValueError('Each hypothesis is an object')
        rec=dict(id=f'z{i}',description=text(r.get('description'),'description'))
        for name in ('functions','assumptions'):
            if not isinstance(r.get(name),list):raise ValueError(name+' must be an array')
            rec[name]=[text(v,name) for v in r[name]]
        result.append(rec)
    return result


