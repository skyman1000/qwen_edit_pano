def contents_answer(value,case,furniture):
    rows=value.get('bundles');groups={g['key']:g for g in furniture['groups']};observed={o['id'] for o in case['context']}
    if not isinstance(rows,list) or len(rows)!=len(groups) or any(not isinstance(r,dict) for r in rows):raise ValueError('Return exactly one bundle mechanism per group')
    if {r.get('group') for r in rows}!=set(groups):raise ValueError('Copy every supplied group ID once')
    result={};errors=[];furniture_keys={o['key'] for g in groups.values() for o in g['objects']}
    for r in rows:
        gid=r['group'];alts=r.get('alternatives');out=[]
        if not isinstance(alts,list) or not 1<=len(alts)<=2:raise ValueError('Content alternatives needs 1..2 records, possibly empty')
        hosts={o['key'] for o in groups[gid]['objects']}
        for ai,a in enumerate(alts):
            if not isinstance(a,dict):raise ValueError('Content alternative must be an object')
            at=f'bundles[{gid}].alternatives[{ai}]'
            try:
                objects=objects_answer(a.get('objects'),observed,hosts,max_objects=12,path=at+'.objects')
                collisions={o['key'] for o in objects}&furniture_keys
                if collisions:raise ValueError(at+': NEW content keys collide with existing furniture '+str(sorted(collisions)))
                available=observed|furniture_keys|{o['key'] for o in objects}
                relations,bindings=relations_answer(a.get('relations',[]),available,objects,path=at+'.relations')
                out.append(dict(description=text(a.get('description'),'content description'),objects=objects,
                    relations=relations,relation_bindings=bindings))
            except ValueError as exc:errors.append(str(exc))
        result[gid]=out
    if errors:raise ValueError('Correct ALL invalid content alternatives; no partial mechanism was accepted: '+
        json.dumps(dict(content_contract_errors=errors),ensure_ascii=False))
    if sum(max(len(a['objects']) for a in alts) for alts in result.values())>12:
        raise ValueError('Largest joint contents exceeds total capacity 12; preserve originals and reduce proposed capacity explicitly')
    seen=set()
    for gid,alts in result.items():
        keys={o['key'] for a in alts for o in a['objects']}
        if seen&keys:raise ValueError('Content keys must be unique across assemblies; alternative variants within one assembly may reuse a key')
        seen|=keys
    return result


def build_model(hypotheses,furnitures,contents):
    nodes=[];records={};fids=list(furnitures)
    def add(name,states,parents,mechanism):
        domains={n['id']:n['states'] for n in nodes};table={}
        for values in itertools.product(*(domains[p] for p in parents)):
            given=dict(zip(parents,values));table[key(values)]=mechanism(given,states)
        nodes.append(dict(id=name,states=states,parents=parents,cpt=table))
    def one(states,wanted):return [float(s==wanted) for s in states]
    add('Z',[z['id'] for z in hypotheses],[],lambda g,s:[1/len(s)]*len(s))
    def furniture_law(g,states):
        active=[fid for fid in states if furnitures[fid]['hypothesis']['id']==g['Z']]
        return [float(fid in active)/len(active) for fid in states]
    add('F',fids,['Z'],furniture_law)
    for fid,f in furnitures.items():
        for group in f['groups']:
            gid=group['key'];alts=contents[fid][gid];tid=f'T_{fid}_{gid}'
            add(tid,['off']+[str(i) for i in range(len(alts))],['F'],
                lambda g,s,fid=fid:one(s,'off') if g['F']!=fid else [0.]+[1/(len(s)-1)]*(len(s)-1))
            # Union of typed components, but every content alternative has its
            # own identities. The SAME host presence gates all its dependants.
            for alt_index,alt_objects in [(-1,group['objects'])]+[(j,a['objects']) for j,a in enumerate(alts)]:
                prefix=f'{fid}_{gid}_'+('base_' if alt_index<0 else f'c{alt_index}_')
                local_keys={o['key']:prefix+o['key'] for o in alt_objects}
                furniture_ids={o['key']:f'{fid}_{gid}_base_'+o['key'] for o in group['objects']}
                external={o['attachment']['host'] for o in alt_objects if o['attachment']['host'] not in local_keys}
                for obj in order_objects(alt_objects,external):
                    oid=local_keys[obj['key']];host=obj['attachment']['host'];host_id=(local_keys.get(host) or furniture_ids.get(host)) if host else None
                    # Observed hosts are fixed context and need no presence node.
                    host_node='P_'+host_id if host_id else None
                    pnode='P_'+oid;parents=['F']+([tid] if alt_index>=0 else [])+([host_node] if host_node else [])
                    def present(g,s,fid=fid,ai=alt_index,tid=tid,hn=host_node):
                        active=g['F']==fid and (ai<0 or g[tid]==str(ai)) and (hn is None or g[hn]=='1')
                        return one(s,'1' if active else '0')
                    add(pnode,['0','1'],parents,present)
                    rec=deepcopy(obj);rec.update(id=oid,presence_node=pnode,group=gid,furniture_state=fid,content_alternative=alt_index)
                    rec['attachment']['host']=host_id or host
                    records[oid]=rec
    model=validate(dict(protocol=PROTOCOL,nodes=nodes,component_registry=records,
        hypotheses=deepcopy(hypotheses),furniture_states=deepcopy(furnitures),contents_mechanisms=deepcopy(contents),
        distribution_scope='uniform_reference_law_conditional_on_image_proposed_finite_grammar',
        RGB_likelihood_defined=False,calibrated_posterior_defined=False,real_causal_structure_identified=False,
        intervention_scope='generative_installed_component_presence_not_dynamic_object_removal'))
    return model


def active_world(model,state):
    objects=[deepcopy(o) for o in model['component_registry'].values() if state[o['presence_node']]=='1']
    f=model['furniture_states'][state['F']];mapping={}
    for obj in objects:mapping[obj['key']]=obj['id']
    # Local content keys may be repeated across mutually exclusive alternatives,
    # but active keys must be unique for explicit relation references.
    if len(mapping)!=len(objects):raise ValueError('Selected contents repeat an identity across groups')
    relations=deepcopy(f['relations'])
    for g in f['groups']:
        choice=state[f'T_{state["F"]}_{g["key"]}']
        if choice!='off':relations+=deepcopy(model['contents_mechanisms'][state['F']][g['key']][int(choice)]['relations'])
    translated=[{**r,'source':mapping.get(r['source'],r['source']),'target':mapping.get(r['target'],r['target'])} for r in relations
        if (r['source'] not in {o['key'] for o in model['component_registry'].values()} or r['source'] in mapping)
        and (r['target'] not in {o['key'] for o in model['component_registry'].values()} or r['target'] in mapping)]
    return dict(configuration=f['description'],hypothesis=f['hypothesis'],objects=objects,groups=deepcopy(f['groups']),relations=translated,
        structural_state=deepcopy(state))


def sample_worlds(model,seed=3407,count=3):
    rng=np.random.default_rng(seed);worlds=[];seen=set()
    for trial in range(128):
        noise={n['id']:float(rng.random()) for n in model['nodes']};state=forward(model,noise)
        world=active_world(model,state);signature=tuple(sorted(o['id'] for o in world['objects']))
        if signature in seen:continue
        seen.add(signature);world.update(noise=noise,seed=seed,trial=trial);worlds.append(world)
        if len(worlds)>=count:break
    return worlds


def intervention_diagnostics(model,world):
    rows=[];before={o['id'] for o in world['objects']}
    for obj in world['objects']:
        descendants=[o for o in world['objects'] if o['attachment']['host']==obj['id']]
        if not descendants:continue
        do={obj['presence_node']:'0'};state=forward(model,world['noise'],do);after=active_world(model,state)
        ids={o['id'] for o in after['objects']}
        rows.append(dict(do=do,host=obj['id'],before=sorted(before),after=sorted(ids),
            removed=sorted(before-ids),same_exogenous_noise=True,model_called=False))
    return dict(queries=rows,scope=model['intervention_scope'],causal_gain_validated=False)
