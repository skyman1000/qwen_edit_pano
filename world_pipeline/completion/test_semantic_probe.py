"""Probe separation and provenance checks; no assertions about LLM capability."""
from copy import deepcopy
from pathlib import Path
import tempfile
import unittest

from PIL import Image

from ..common import read, sha, write
from .semantic_probe import load_cases, prompt, run, scene_contents_prompt, state_context, validate_answer
from .semantic_world import make_graph
from .test_semantic_world import fixture


def state():
    observed, _, layout = fixture()
    return make_graph(observed, layout, 'test', 'predicted', 'observed')


def answer():
    return dict(scene_type='bedroom', scene_hypothesis='A sleeping area with a storage corner.',
        additions=[dict(id='new_0', name='a specific unseen storage object',
                       reason='Storage for the sleeping area.', placement='Outside the photo to the left.')])


class SemanticProbeTests(unittest.TestCase):
    def test_retains_predicted_fields_without_changing_observations_or_using_gt(self):
        graph = state()
        original = deepcopy(graph)
        context = state_context(graph)
        self.assertEqual(graph, original)
        self.assertEqual(context[0]['center'], graph['objects'][0]['center_local_m']['value'])
        self.assertEqual(context[0]['description'], graph['objects'][0]['description'])
        graph['stage'] = 'gt'
        with self.assertRaises(ValueError):
            state_context(graph)

    def test_semantics_not_filtered_by_adapter_taxonomy_or_forced_addition_count(self):
        context = state_context(state())
        raw = answer()
        self.assertIsNone(validate_answer(raw, context)[0]['adapter_category'])
        self.assertEqual(raw, answer())
        raw['additions'] = []
        self.assertEqual(validate_answer(raw, context), [])
        raw = answer()
        raw['additions'][0]['id'] = context[0]['id']
        with self.assertRaises(ValueError):
            validate_answer(raw, context)

    def test_scene_contents_variant_reuses_identical_evidence_without_forced_furniture(self):
        context = state_context(state())
        before = deepcopy(context)
        baseline = prompt(context, 90)
        variant = scene_contents_prompt(context, 90)
        self.assertEqual(context, before)
        self.assertEqual(baseline.split('FIXED OBSERVATIONS: ')[1], variant.split('FIXED OBSERVATIONS: ')[1])
        self.assertNotEqual(baseline, variant)
        self.assertIn('coarse detector summary', variant)
        self.assertIn('scene continuation', variant)
        # Functional suggestions are generated by the model, not copied from a fixed menu.
        self.assertNotIn('bookshelf', variant)
        self.assertNotIn('coffee table', variant)

    def test_fixed_inputs_paired_requests_review_and_no_full_state(self):
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            observer = root/'batch/case/observer_001'
            observer.mkdir(parents=True)
            image = observer/'input.png'
            Image.new('RGB', (32, 32)).save(image)
            write(observer/'G_obs.json', state())
            write(observer/'config.json', dict(image=str(image), image_sha256=sha(image), hfov_deg=90))
            # Deliberate GT/room-label decoys must never enter the prompt.
            write(root/'batch/summary.json', dict(secret='GT_ROOM_LABEL_DO_NOT_READ'))
            cases = load_cases(root/'batch', None)
            self.assertNotIn('GT_ROOM_LABEL_DO_NOT_READ', cases[0]['prompt'])
            self.assertEqual(cases[0]['prompt'], prompt(cases[0]['context'], 90))
            calls = []
            class Model:
                def ask(self, image, question, path, **kwargs):
                    calls.append((image, question, kwargs))
                    raw = answer()
                    raw['scene_hypothesis'] += '<script>alert(1)</script>'
                    write(path.with_suffix('.json'), raw)
                    return raw
            output = root/'out'
            output.mkdir()
            self.assertTrue(run(Model(), cases, output, ['state', 'image_state'], 3407, 4096))
            self.assertIsNone(calls[0][0])
            self.assertIsInstance(calls[1][0], Image.Image)
            self.assertEqual(calls[0][1:], calls[1][1:])
            self.assertFalse((output/'G_full.json').exists())
            self.assertFalse(read(output/'summary.json')['semantics_verified'])
            self.assertIn('&lt;script&gt;', (output/'review.html').read_text())
            image.write_bytes(b'changed')
            with self.assertRaisesRegex(ValueError, 'image changed'):
                load_cases(root/'batch', None)


if __name__ == '__main__':
    unittest.main()
